app.post('/api/chat', async (req, res) => {
  const { character, message } = req.body;

  if (!character || !message) {
    return res.status(400).json({ error: 'character 또는 message가 누락됨' });
  }

  try {
    const chat = await getOrCreateChat(character);
    const result = await chat.sendMessage(message);
    const reply = result.response.text();

    // ✅ 최근 대화 저장
    if (!chatLogs[character]) chatLogs[character] = [];
    chatLogs[character].push({ user: message, ai: reply });

    // 5쌍 초과 시 앞에서 자르기
    if (chatLogs[character].length > 3) {
      chatLogs[character] = chatLogs[character].slice(-3);
    }


    // 대화 카운트 증가
    // if (!chatCounts[character]) chatCounts[character] = 0;
    // chatCounts[character] += 1;

    // // 쌍으로 세기 때문에 2로 나눠서 몫만 따짐
    // const pairCount = Math.floor(chatCounts[character] / 2);
    const pairCount = chatLogs[character]?.length || 0;
    const eventReady = pairCount >= 3;

    res.json({ reply, eventReady });
  } catch (err) {
    console.error('[Gemini 오류]', err);
    res.status(500).json({ error: 'Gemini 응답 실패' });
  }
});

